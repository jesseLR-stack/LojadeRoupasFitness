-- Atualização 3: contas de clientes, avaliações e cupons gerenciados pelo painel.
-- Como usar: no Supabase, abra "SQL Editor", cole este arquivo inteiro e clique em "Run".
-- Pode rodar mais de uma vez sem problema.

-- 1. Clientes (login feito pelo próprio site; a senha fica guardada com hash scrypt, nunca em texto).
create table if not exists public.customers (
  id            bigint generated by default as identity primary key,
  name          text not null,
  email         text not null unique,
  password_hash text not null,
  created_at    timestamptz not null default now()
);

-- 2. Pedido ligado à conta do cliente (opcional: dá para comprar sem conta).
alter table public.orders add column if not exists customer_id bigint references public.customers(id) on delete set null;
create index if not exists orders_customer_idx on public.orders (customer_id, created_at desc);

-- 3. Avaliações: uma por cliente por produto, só de quem recebeu o produto.
create table if not exists public.reviews (
  id           bigint generated by default as identity primary key,
  product_id   bigint not null references public.products(id) on delete cascade,
  customer_id  bigint not null references public.customers(id) on delete cascade,
  order_number text not null,
  author       text not null,
  rating       smallint not null check (rating between 1 and 5),
  comment      text not null default '',
  created_at   timestamptz not null default now(),
  unique (product_id, customer_id)
);
create index if not exists reviews_product_idx on public.reviews (product_id, created_at desc);

-- 4. Cupons de desconto.
create table if not exists public.coupons (
  code       text primary key check (code = upper(code) and length(code) between 3 and 30),
  percent    smallint not null check (percent between 1 and 90),
  active     boolean not null default true,
  expires_at date,
  max_uses   integer check (max_uses is null or max_uses > 0),
  uses       integer not null default 0,
  created_at timestamptz not null default now()
);
insert into public.coupons (code, percent) values ('NEW10', 10), ('TREINO15', 15) on conflict (code) do nothing;

-- Conta um uso do cupom, só se ele ainda for válido. Devolve false se não puder ser usado.
create or replace function public.use_coupon(c text) returns boolean
language plpgsql security definer set search_path = public as $$
declare changed int;
begin
  update coupons set uses = uses + 1
   where code = upper(c) and active
     and (expires_at is null or expires_at >= (now() at time zone 'America/Sao_Paulo')::date)
     and (max_uses is null or uses < max_uses);
  get diagnostics changed = row_count;
  return changed > 0;
end $$;

-- Segurança: tudo fechado para acesso público; só o servidor da loja (chave secreta) acessa.
alter table public.customers enable row level security;
alter table public.reviews enable row level security;
alter table public.coupons enable row level security;
revoke all on public.customers, public.reviews, public.coupons from anon, authenticated;
grant select, insert, update, delete on public.customers, public.reviews, public.coupons to service_role;
grant usage, select on all sequences in schema public to service_role;
revoke all on function public.use_coupon(text) from public, anon, authenticated;
grant execute on function public.use_coupon(text) to service_role;
