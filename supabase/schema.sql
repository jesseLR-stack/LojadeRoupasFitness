-- Estrutura do banco da NewFitness.
-- Como usar: no Supabase, abra "SQL Editor", cole este arquivo inteiro e clique em "Run".
-- Pode rodar mais de uma vez sem problema.

create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  slug        text not null unique,
  name        text not null,
  description text not null default '',
  category    text not null,
  gender      text not null,
  collections text[] not null default '{}',
  colors      text[] not null default '{}',
  sizes       text[] not null default '{}',
  price       numeric(10,2) not null check (price > 0),
  old_price   numeric(10,2),
  rating      numeric(2,1) not null default 5,
  reviews     integer not null default 0,
  tag         text not null default '',
  is_new      boolean not null default false,
  stock       integer not null default 0 check (stock >= 0),
  active      boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.orders (
  number       text primary key,
  status       text not null default 'novo'
               check (status in ('novo', 'pago', 'enviado', 'entregue', 'cancelado')),
  customer     jsonb not null,
  items        jsonb not null,
  ship         text not null,
  pay          text not null,
  installments integer not null default 1,
  coupon       text,
  subtotal     numeric(10,2) not null,
  discount     numeric(10,2) not null default 0,
  pix_discount numeric(10,2) not null default 0,
  shipping     numeric(10,2) not null default 0,
  total        numeric(10,2) not null,
  created_at   timestamptz not null default now()
);

create index if not exists orders_created_at_idx on public.orders (created_at desc);

-- Atualiza updated_at automaticamente.
create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

drop trigger if exists products_touch on public.products;
create trigger products_touch before update on public.products
  for each row execute function public.touch_updated_at();

-- Baixa o estoque de todos os itens do pedido de uma vez.
-- Se algum item não tiver estoque, nada é alterado e a função devolve erro "sem_estoque:<id>".
create or replace function public.reserve_stock(items jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare
  it jsonb;
  changed int;
begin
  for it in select * from jsonb_array_elements(items) loop
    update products
       set stock = stock - (it->>'qty')::int
     where id = (it->>'id')::bigint and active and stock >= (it->>'qty')::int;
    get diagnostics changed = row_count;
    if changed = 0 then
      raise exception 'sem_estoque:%', it->>'id';
    end if;
  end loop;
end $$;

-- Usado depois de importar os produtos iniciais com ids fixos.
create or replace function public.sync_products_id_seq() returns void
language sql security definer set search_path = public as $$
  select setval(pg_get_serial_sequence('products', 'id'), coalesce((select max(id) from products), 1));
$$;

-- Segurança: as tabelas ficam fechadas para acesso público.
-- Só o servidor da loja (com a chave service_role, que nunca vai para o navegador) lê e grava.
alter table public.products enable row level security;
alter table public.orders enable row level security;

revoke all on function public.reserve_stock(jsonb) from public, anon, authenticated;
revoke all on function public.sync_products_id_seq() from public, anon, authenticated;
grant execute on function public.reserve_stock(jsonb) to service_role;
grant execute on function public.sync_products_id_seq() to service_role;
